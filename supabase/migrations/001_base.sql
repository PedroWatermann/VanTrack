-- Empresa, vans e motoristas -------------------------------------------------

create table empresa (
  id   bigint generated by default as identity primary key,
  nome text not null,
  cnpj text not null unique
);

create table van (
  id         bigint generated by default as identity primary key,
  empresa_id bigint not null references empresa (id),
  placa      text   not null unique,
  modelo     text   not null,
  capacidade int    not null check (capacidade > 0)
);

-- Motorista e Responsavel são Usuarios (diagrama de classes 1/3): id, nome, login
-- e senha_hash. A senha é opcional: a C-02 decide se o login simplificado a usa
-- (ponto 1 da seção 3 do 03-arquitetura.md).
create table motorista (
  id         bigint generated by default as identity primary key,
  empresa_id bigint not null references empresa (id),
  nome       text   not null,
  login      text   not null unique,
  senha_hash text,
  telefone   text   not null,
  cnh        text   not null
);

-- Histórico de quais vans cada motorista dirigiu (RF-014).
create table vinculo_motorista_van (
  id           bigint generated by default as identity primary key,
  motorista_id bigint      not null references motorista (id),
  van_id       bigint      not null references van (id),
  inicio       timestamptz not null default now(),
  fim          timestamptz,
  check (fim is null or fim > inicio)
);

-- RN-012: só um motorista ativo (vínculo sem fim) por van.
create unique index vinculo_motorista_van_um_ativo_por_van
  on vinculo_motorista_van (van_id)
  where fim is null;

-- Famílias e alunos ----------------------------------------------------------

create table responsavel (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  login      text not null unique,
  senha_hash text,
  telefone   text not null,
  email      text not null
);

create table aluno (
  id                bigint generated by default as identity primary key,
  nome              text not null,
  -- RN-009: a data de nascimento define se o aluno é menor.
  data_nascimento   date not null,
  situacao_cadastro text not null default 'ATIVO'
    check (situacao_cadastro in ('PENDENTE', 'ATIVO', 'INATIVO'))
);

-- Vínculo aluno–responsável (N:N). RN-002: o responsável só vê os seus alunos.
create table aluno_responsavel (
  aluno_id       bigint not null references aluno (id) on delete cascade,
  responsavel_id bigint not null references responsavel (id) on delete cascade,
  primary key (aluno_id, responsavel_id)
);

-- Operação diária ------------------------------------------------------------

create table ponto_parada (
  id        bigint generated by default as identity primary key,
  endereco  text             not null,
  latitude  double precision not null,
  longitude double precision not null
);

create table rota (
  id               bigint generated by default as identity primary key,
  van_id           bigint not null references van (id),
  data             date   not null,
  trajeto          text   not null check (trajeto in ('IDA', 'VOLTA')),
  horario_previsto time   not null,
  situacao         text   not null default 'PLANEJADA'
    check (situacao in ('PLANEJADA', 'ATIVA', 'CONCLUIDA', 'CANCELADA')),
  -- Uma rota por van, por dia e por trajeto.
  unique (van_id, data, trajeto)
);

-- Presença de um aluno em uma rota, com a ordem da parada.
-- RN-010 (exceção): presença AUSENTE não entra na rota do dia.
create table presenca (
  id                      bigint generated by default as identity primary key,
  rota_id                 bigint      not null references rota (id) on delete cascade,
  aluno_id                bigint      not null references aluno (id),
  ponto_parada_id         bigint      not null references ponto_parada (id),
  ordem                   int         not null check (ordem > 0),
  situacao                text        not null
    check (situacao in ('CONFIRMADO', 'AUSENTE', 'EMBARCADO')),
  data_hora_confirmacao   timestamptz,
  data_hora_cancelamento  timestamptz,
  unique (rota_id, aluno_id),
  unique (rota_id, ordem)
);

-- Registro do embarque feito pelo motorista (RF-009, RN-010, RNF-006).
create table embarque (
  id           bigint generated by default as identity primary key,
  -- UUID gerado no aparelho: torna o envio idempotente (RNF-006).
  registro_id  uuid             not null,
  presenca_id  bigint           not null references presenca (id) on delete cascade,
  -- Momento do toque no aparelho, não o do envio.
  data_hora    timestamptz      not null,
  latitude     double precision,
  longitude    double precision,
  -- Sem coluna "sincronizado": no servidor todo embarque gravado já está
  -- sincronizado; a fila fica no aparelho (ponto 10 do 03-arquitetura.md).
  criado_em    timestamptz      not null default now(),
  constraint embarque_registro_id_unico unique (registro_id),
  -- Uma presença gera no máximo um embarque (composição Presenca 1 — 0..1 Embarque).
  -- As duas unicidades viram EmbarqueDuplicadoException no repositório (ponto 4).
  constraint embarque_presenca_id_unico unique (presenca_id),
  -- Localização é opcional ("quando disponível"), mas vem completa ou não vem.
  check ((latitude is null) = (longitude is null))
);

-- Login simplificado (apoio, Membro C): um token (UUID) por sessão.
create table sessao (
  token          uuid        primary key,
  papel          text        not null check (papel in ('MOTORISTA', 'RESPONSAVEL')),
  motorista_id   bigint      references motorista (id) on delete cascade,
  responsavel_id bigint      references responsavel (id) on delete cascade,
  criada_em      timestamptz not null default now(),
  check (
    (papel = 'MOTORISTA'   and motorista_id   is not null and responsavel_id is null) or
    (papel = 'RESPONSAVEL' and responsavel_id is not null and motorista_id   is null)
  )
);

-- Segurança (RNF-002) --------------------------------------------------------
-- RLS ativado e SEM policies: bloqueia o acesso público pela API automática do
-- Supabase. O backend continua acessando porque conecta como dono do banco.

alter table empresa               enable row level security;
alter table van                   enable row level security;
alter table motorista             enable row level security;
alter table vinculo_motorista_van enable row level security;
alter table responsavel           enable row level security;
alter table aluno                 enable row level security;
alter table aluno_responsavel     enable row level security;
alter table ponto_parada          enable row level security;
alter table rota                  enable row level security;
alter table presenca              enable row level security;
alter table embarque              enable row level security;
alter table sessao                enable row level security;
