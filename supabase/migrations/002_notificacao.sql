-- VT-41 (C-01) — Persistência dos avisos do UC-I02 / RF-011.
-- Destinatário e aluno serão usados pelo serviço de notificação (RN-002, RN-009).

create table notificacao (
  id                bigint generated by default as identity primary key,
  tipo              text        not null check (tipo = 'EMBARQUE'),
  responsavel_id    bigint      not null references responsavel (id),
  aluno_id          bigint      not null references aluno (id),
  mensagem          text        not null,
  data_hora_evento  timestamptz not null,
  lida              boolean     not null default false
);

-- RNF-002: bloqueia a API pública do Supabase; o backend usa a conexão do banco.
alter table notificacao enable row level security;
